def get_template(title):
    """根据章节标题获取推荐的模板题ID"""
    tags = get_chapter_tags(title)
    if tags:
        for t in tags:
            if t in TEMPLATE_MAP:
                return TEMPLATE_MAP[t]
    return TEMPLATE_MAP.get('GENERAL')

def get_chapter_tags(title):
    # 按 key 长度降序匹配，优先匹配更精确的标题
    for keyword in sorted(CHAPTER_TAG_MAP, key=len, reverse=True):
        if keyword in title:
            return CHAPTER_TAG_MAP[keyword]
    return ['GENERAL']

